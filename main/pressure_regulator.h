#pragma once

#include <stdbool.h>
#include <stdint.h>

// Глубина кольца чекпойнтов детекции потока в быстром поиске порога (идея 3):
// лаги search_hist_dt_us * (1..N). При dt=0.25с и N=4 -> 0.25/0.5/0.75/1.0 с.
#define SEARCH_HIST_N 4

// Глубина кольца чекпойнтов МУЛЬТИОКОННОЙ проверки прогресса в HOLD/FINE (та же
// идея, что и в поиске порога): лаги dose_hist_dt_us * (1..N). При dt=1.25с и N=4
// -> 1.25/2.5/3.75/5.0 с. Защитные направления (разгон/утечка в HOLD, дрейф в
// FINE) реагируют по ЛЮБОМУ лагу сразу; «медленно/хорошо/равновесие» — по
// длинному 5с окну. Пороги статичные (не масштабируются под длину лага).
#define DOSE_HIST_N 4

// Глубина кольца КОРОТКИХ лагов «сторожа подскока» после прыжка через мёртвый ход
// (см. dose_deadtravel_jump): лаги jump_hist_dt_us * (1..N). При dt=0.15с и N=4 ->
// 0.15/0.30/0.45/0.60 с. Работает ТОЛЬКО пока сторожим (сразу после прыжка): ловит
// резкий подскок давления, чтобы мгновенно откатить иглу, пока поток не «улетел».
#define JUMP_HIST_N 4

// ============================================================================
//  КАСКАДНЫЙ РЕГУЛЯТОР ДАВЛЕНИЯ (rate-control + тонкая I-доводка)
// ----------------------------------------------------------------------------
//  Идея в двух словах:
//
//    ВНЕШНИЙ слой  : ошибка по давлению -> ЖЕЛАЕМАЯ СКОРОСТЬ dP/dt (таблица).
//                    Далеко от цели хотим быстро, близко — медленно.
//                    Это, по сути, профиль приближения ("умная рампа").
//
//    ВНУТРЕННИЙ PI : держит РЕАЛЬНУЮ скорость dP/dt равной желаемой,
//                    выход = открытие иглы (шаги). Коэффициенты ФИКСИРОВАННЫЕ
//                    (настраиваются один раз) — связь "игла->расход->скорость"
//                    почти линейна по всему диапазону, поэтому адаптировать
//                    коэффициенты не нужно: нелинейность объекта (расход слабеет
//                    у цели) гасится самой обратной связью по скорости.
//
//    У ЦЕЛИ        : фаза HOLD (с |error| <= hold_enter_err PID выключен совсем).
//                    В покое объём ЗАПЕЧАТАН: игла на valve_flow_floor (ниже
//                    порога потока), серво в нейтрали — газ из трубки серво->игла
//                    не сочится в объём (подтверждённая причина ползучести).
//                    Коррекции — МИКРОДОЗЫ: серво в нужную сторону, игла на
//                    фиксированном дозирующем открытии step_holding_charge/vent;
//                    раз в 5 с открытие подстраивается по ФАКТИЧЕСКОМУ прогрессу
//                    давления за окно (а не по dP/dt — у цели нужные 0.01-0.02
//                    кПа/с тонут в шуме измерения скорости). Ошибка дошла до
//                    порога печати — игла на парковку, серво в нейтраль.
//
//    ТОЧНЫЙ ХОЛДИНГ : (вкл. конфигом hold_fine_enable) как только НАБОРОМ вышли
//                    на точку и доза подобрана делом — объём НЕ печатаем: серво
//                    остаётся в НАБОРЕ, игла на step_holding_charge-fine_seed_back,
//                    дальше раз в fine_period_us +-fine_trim по знаку скорости
//                    (росло давление за окно -> прикрыть, падало -> приоткрыть).
//                    Игла ищет приоткрытие, где приток равен утечке, и стоит на
//                    нём БЕЗ периодических подкачек. Смещение от цели (просадка
//                    за время поиска и т.п.) лечится СДВИГОМ равновесия: окно
//                    показало «стоим» (|dP| < fine_eq_band), но дальше
//                    fine_corr_err от цели -> само равновесие мягко двигаем
//                    на fine_trim в сторону цели. Запекать
//                    равновесие через печать/докачку нельзя — пока объём запечатан,
//                    магистраль успевает измениться и значение протухает
//                    (проверено: найденные 3393 после докачки уже лили).
//                    Выход на точку СБРОСОМ сюда не ведёт: печатаем, ждём
//                    естественного стравливания вниз, эпизод НАБОРА подбирает
//                    дозу и выводит на точку — и только тогда включается точный
//                    холдинг. Увод дальше hold_enter_err — возврат в обычный
//                    HOLD (эпизоды); повторный вход FINE стартует с найденного
//                    равновесия и дальше подстраивает его окнами как обычно.
//
//    ВЫБОР НАПРАВЛЕНИЯ ПО ДРЕЙФУ (этап «поиск скорости»): нужен ТОЛЬКО при подходе
//                    СБРОСОМ. ПОДХОД НАБОРОМ дрейф НЕ замеряет: раз дошли накачкой,
//                    объём травит вниз — удержание ВСЕГДА НАБОРОМ (берём утечку за
//                    правду), сразу fine_dir=НАБОР и в FINE, без запечатывания/паузы.
//                    ПОДХОД СБРОСОМ (поведение запечатанного объёма заранее неясно):
//                    СНАЧАЛА поиск порога потока СБРОСА (перебор от seed вверх, как у
//                    набора), который выводит P к цели, ПОТОМ объём ДЕРЖИМ запечатанным
//                    (серво в нейтрали, игла floor): пауза 1с + замер дрейфа P_filt за
//                    fine_ss_period_us (3 с). Запечатываем не на цели, а на
//                    (цель + fine_ss_vent_offset) — запас вниз на просадку за время
//                    замера. |dP| < fine_ss_seal_band (объём держит давление САМ) ->
//                    FINE НЕ нужен: перекрываем всё (игла 0, серво нейтраль), уходим в
//                    обычный HOLD, направление не фиксируем. Иначе dP<0 (объём травит)
//                    -> удерживаем НАБОРОМ; dP>=0 (ползёт вверх) -> удерживаем СБРОСОМ.
//                    Если у нужного направления ещё НЕТ калиброванной дозы — сперва
//                    ПОИСК ПОРОГА ПОТОКА этого направления (ПОДГОНА УГЛА -> перебор ->
//                    найден−search_done_back), он выводит на точку, и только потом FINE.
//                    Дальше — как описано выше (равновесное приоткрытие + сдвиг
//                    равновесия к цели), знак ±шага иглы задаёт servo_state (hold_fine_step).
//                    Замер делается ОДИН раз на уставку: результат запоминается в
//                    fine_dir (fine_dir_known), повторные входы в FINE сразу берут это
//                    направление БЕЗ нового запечатывания/замера. Сброс памяти — только
//                    новая уставка / reset (иначе каждый вход перемеряет утечку зря).
//
//    ПОИСК ДОЗЫ ПОД НУЖНОЕ НАПРАВЛЕНИЕ (после замера дрейфа): если у выбранного
//                    направления удержания ещё нет калиброванной дозы — её НАХОДИМ
//                    переборным поиском порога потока (как при обычном наборе), а не
//                    садимся во floor. Два симметричных случая:
//                    • dP<0 (объём травит) -> держим НАБОРОМ. Дозы набора при сбросовом
//                      подходе нет (step_holding_charge=floor) -> серво в НАБОР, поиск
//                      порога накачки. Запечатывание на (цель+fine_ss_vent_offset) даёт
//                      запас: поиск идёт, пока утечка ведёт P к цели.
//                    • dP>=0 (объём подпирает вверх) -> держим СБРОСОМ. Готовой дозы
//                      сброса нет -> серво в СБРОС, поиск порога сброса (поток = падение P).
//                    Поиск выводит на точку (шаг удержания = флоу−search_done_back при
//                    остатке < search_target_back), по fine_dir_known проваливаемся в FINE
//                    нужного направления. Перелетели цель — обычный HOLD (эпизод обратного
//                    направления) подводит к ней, FINE включается уже на точке. Направление
//                    уже зафиксировано, повторный замер дрейфа не делается.
//
//  Направление (накачка/сброс) задаёт серво (180/0 град), величину потока —
//  игла (шаговик). Поэтому открытие иглы всегда >= 0, а знак берёт на себя серво.
// ============================================================================

// Положение 3-позиционного серво-крана направления.
typedef enum {
    SERVO_NEUTRAL,   // 90 град — объём изолирован (держим)
    SERVO_CHARGING,  // 180 град — подаём давление
    SERVO_VENTING    // 0 град — стравливаем
} ServoState;

// Состояния автомата регулятора. Снаружи запрашиваются REG_STATE_IDLE и REG_STATE_LEAK.
typedef enum {
    REG_STATE_NONE = 0, // «нет запроса» — служебное значение для requested_reg_state
    REG_STATE_IDLE,     // ничего не делаем, серво в нейтрали, игла закрыта
    REG_STATE_HOMING,   // принудительный физический сброс давления
    REG_STATE_RUNNING,  // активное регулирование (внутри: дальняя/тонкая зона)
    REG_STATE_LEAK,     // одноразовый тест утечки (накачать, запечатать, измерить, стравить)
    REG_STATE_OVERPRESSURE // АВАРИЯ: P > P_MAX_KPA -> аварийно стравить всё и уйти в IDLE
} RegulatorState;

typedef struct {
    // ---- общее ----
    RegulatorState state;
    ServoState     servo_state;     // текущее положение серво (чтобы дёргать его только при смене)
    float          active_setpoint; // уставка, на которой сейчас работаем (для детекта смены цели)

    // ---- измерение скорости (производная давления) ----
    float    prev_pressure;         // давление на прошлом СВЕЖЕМ отсчёте датчика
    uint64_t last_pressure_us;      // время прошлого свежего отсчёта (мкс) — для честного dP/dt
    float    raw_rate;              // сырая dP/dt (без фильтра) — только для лога/сравнения
    float    filtered_rate;         // отфильтрованная dP/dt, кПа/с
    float    rate_filter_alpha;     // коэф. фильтра скорости (0..1, ближе к 1 = сильнее сглаживание)
    float    filtered_pressure;     // отфильтрованное давление (EMA) — порог HOLD считаем по нему
    float    press_filter_alpha;    // коэф. фильтра давления (0..1, ближе к 1 = сильнее сглаживание)
    uint16_t glitch_skips;          // подряд отброшенных «битых» отсчётов датчика (анти-залипание)

    // ---- ВНУТРЕННИЙ PI по скорости (дальняя зона) ----
    float   rate_kp;                // реакция на отклонение скорости (шаги на кПа/с)
    float   rate_ki;               // набор стационарного открытия (шаги на кПа/с * с)
    float   rate_integral;          // интегратор внутреннего контура (только >= 0)
    float   rate_integral_max;      // ограничение интегратора (anti-windup)

    // ---- порог шума датчика / ползучая скорость у цели ----
    float sensor_noise_delta;       // макс. дрожание датчика в покое (кПа). Двойная роль:
                                    //  - порог ВЫХОДА из холда (|error| больше -> снова регулируем);
                                    //  - в полосе error 0..2 = желаемая скорость подхода к цели.
    float sensor_noise_delta_filt; // а это тоже самое но с учетом фильтра 80%-20%

    // ---- состояние холда: в покое ЗАПЕЧАТАНО (игла на valve_flow_floor, серво
    //      нейтраль), коррекция = серво задаёт направление + игла на фиксированном
    //      дозирующем открытии (МИКРОДОЗА); открытие подстраивается раз в окно по
    //      фактическому прогрессу давления, без PI ----
    bool     holding;               // true = фаза HOLD (PID выключен до новой уставки)
    float    hold_enter_err;        // |error| <= этого -> RATE выключается, входим в HOLD
    float    hold_exit_err;         // в HOLD |err_filt| > этого -> назад в RATE качать (гистерезис со hold_enter_err)
    float    hold_lead_close_s;     // УПРЕЖДЕНИЕ входа в HOLD = «время закрытия иглы», с. Пока RATE едет к
                                    // цели, игла широко открыта; за время закрытия P ещё уйдёт
                                    // |rate|*это. Отдаём в HOLD, когда остаток до цели <= |rate|*это
                                    // (тормозной путь). Берём большее из него и hold_enter_err. 0 = выкл.
    int32_t  rate_approach_sign;    // БЫСТРЫЙ РЕЖИМ: с какой стороны цели стартовал подход
                                    // (+1 = снизу/НАБОР, −1 = сверху/СБРОС). Сменился знак error_filt
                                    // относительно него -> цель пересечена -> «дошли» (перелёт допустим).
                                    // 0 = ещё не зафиксирован (далеко не отъехали / уже у цели).
    int32_t  dose_step_back;        // вход в HOLD набором: старт свипа поиска порога = позиция RATE минус это
    int32_t  step_holding_charge;   // дозирующее открытие иглы для НАБОРА (живёт между эпизодами)
    int32_t  step_holding_vent;     // то же для СБРОСА (перепад на игле другой — своё значение)
    bool     dose_charge_calibrated; // false: доза НАБОРА ещё ни разу не дала потока (засеяна floor'ом)
                                     // -> в ветке «медленно» прибавляем dose_trim_big, а не dose_trim
    bool     dose_vent_calibrated;   // то же для СБРОСА
    uint64_t dose_t0_us;            // начало текущего окна проверки прогресса (мкс)
    float    dose_p0;               // P_filt в начале окна
    uint64_t dose_period_us;        // длительность окна проверки (5 с)
    float    dose_dp_slow;          // прогресс за окно МЕНЬШЕ -> приоткрыть на dose_trim
    float    dose_dp_VERYslow;      // прогресс за окно В ОБРАТНУЮ СТОРОНУ -> открыть сильно на dose_trim_big
    float    dose_dp_fast;          // прогресс БОЛЬШЕ -> прикрыть на dose_trim
    float    dose_dp_runaway;       // прогресс СИЛЬНО больше -> прикрыть на dose_trim_big
    int32_t  dose_trim;             // мелкий шаг подстройки открытия (шаги иглы)
    int32_t  dose_trim_big;         // грубый шаг подстройки при разгоне
    int32_t  dose_trim_very_big;         // очень грубый шаг подстройки до калиброки угла на точке
    // СБРОС (откачивание) на низком давлении: поток через иглу слабый (мал перепад),
    // мелким шагом дозу не выгрести -> при P(СЫРОЕ) < dose_lowvent_max берём крупный
    // шаг ВМЕСТО dose_trim / dose_trim_big. Только для сброса (charging==false).
    int32_t  dose_trim_lowvent;     // замена dose_trim     на низком сбросе
    int32_t  dose_trim_big_lowvent; // замена dose_trim_big на низком сбросе
    float    dose_lowvent_max;      // порог давления (кПа): ниже -> крупный шаг сброса
    float   dose_lowvent_p_low;      // нижняя граница интерп. откачивания: ≤этого → крупный шаг (20/50)
    int32_t dose_vent_reduce_count;  // счётчик подряд-опусканий при откачивании (аварийный /2)
    float    dose_big_min_err;      // п.1: |уставка − P(СЫРОЕ)| меньше этого -> big/very_big НЕ применяем,
                                    // берём обычный dose_trim (близко к цели крупный шаг переливает)

    // ---- п.2: МУЛЬТИОКОННАЯ проверка прогресса (кольцо лагов, как в поиске порога) ----
    // Чекпойнты P_filt раз в dose_hist_dt_us -> лаги 1.25..5с. Защитные направления
    // (разгон>runaway / утечка<VERYslow в HOLD; дрейф>=fine_eq_band в FINE) срабатывают
    // по ЛЮБОМУ лагу СРАЗУ. Пороги статичные (как search_dp_flow), окно не масштабируем.
    // Кольцо общее для дозы и FINE: фазы не пересекаются (как и dose_t0_us/dose_p0).
    float    dose_hist[DOSE_HIST_N]; // кольцо чекпойнтов P_filt
    int32_t  dose_hist_idx;         // куда писать следующий чекпойнт
    int32_t  dose_hist_count;       // сколько чекпойнтов валидно (0..N)
    uint64_t dose_hist_dt_us;       // период между чекпойнтами (= младший лаг, 1.25с)
    uint64_t dose_hist_t0_us;       // время последнего чекпойнта

    // ---- ПРОБОЙ МЁРТВОГО ХОДА ПРЫЖКОМ + СТОРОЖ ПОДСКОКА ----
    // Если игла стоит в «мёртвом ходе» (открытие есть, потока нет), ползучий +dose_trim
    // выгребает его десятками секунд. Поэтому: ДВА окна дозы подряд без изменения давления
    // (dose_flat_run >= 2) -> следующий шаг не +dose_trim, а крупный +dose_deadtravel_jump
    // («прыжок»). Прыжок может проскочить порог потока и рвануть мимо цели, поэтому сразу
    // после него ВЗВОДИМ СТОРОЖ: пока сторожим, кольцо коротких лагов 0.15..0.60с следит за
    // подскоком давления к цели (опора — P в момент прыжка). Рвануло (>= dose_jump_spike_dp)
    // по любому лагу -> МГНОВЕННО откат иглы на dose_jump_back_pos (до-прыжковую позицию) и
    // сброс памяти «пустых окон» (чтобы не прыгнуть снова) — дальше цель доводят +dose_trim.
    int32_t  dose_deadtravel_jump;  // шаг прыжка через мёртвый ход (вместо dose_trim после 2 пустых окон)
    int32_t  dose_flat_run;         // подряд окон дозы без изменения P (>=2 -> следующий шаг = прыжок)
    bool     dose_jump_armed;       // true = только что прыгнули, сторожим подскок коротким кольцом
    int32_t  dose_jump_back_pos;    // позиция иглы ДО прыжка — откат сюда при подскоке
    uint64_t dose_jump_t0_us;       // время прыжка (таймаут сторожа = все короткие лаги)
    float    dose_jump_spike_dp;    // подскок к цели больше этого (по любому короткому лагу) -> откат
    float    jump_hist[JUMP_HIST_N];// кольцо коротких чекпойнтов P_filt (живёт только пока сторожим)
    int32_t  jump_hist_idx;         // куда писать следующий чекпойнт
    int32_t  jump_hist_count;       // сколько чекпойнтов валидно (0..N)
    uint64_t jump_hist_dt_us;       // период коротких чекпойнтов (= младший лаг, 0.15с)
    uint64_t jump_hist_t0_us;       // время последнего короткого чекпойнта

    // ---- БЫСТРЫЙ ПОИСК ПОРОГА ПОТОКА (cracking point) перед дозированием ----
    // Вместо медленного +dose_trim за 5 с от floor (мёртвый ход иглы выгребается
    // сотнями секунд) — быстрый свип: +search_step раз в search_step_period_us.
    // Детекция потока по нескольким лагам (см. search_hist ниже): P_filt выросло на
    // search_dp_flow над любым чекпойнтом -> поток пошёл. Иглу НЕ роняем в floor, а
    // держим на найденной позиции и едем вверх до цели; дошли -> калибровка
    // засчитана, дальше обычные микродозы hold_dose_step.
    bool     dose_searching;        // true = идёт быстрый свип порога потока
    int32_t  search_phase;          // 0 = прогрев фильтра, 1 = свип вверх, 2 = едем до цели
    uint64_t search_step_period_us; // период приращения иглы при свипе
    int32_t  search_step;           // приращение иглы за период свипа (шаги)
    uint64_t search_step_t0_us;     // время последнего приращения свипа
    // Детекция потока по НЕСКОЛЬКИМ лагам: кольцо чекпойнтов P_filt (новый раз в
    // search_hist_dt_us). Поток = P_filt поднялось на search_dp_flow над ЛЮБЫМ из
    // чекпойнтов -> крутой старт ловит ближний лаг (~0.25с) почти сразу, пологий —
    // дальний (~1с). Порог по ΔP, НЕ по скорости: иначе ближнее окно (0.25с) при
    // 0.05 кПа/с = +0.0125 кПа ловит шум. Фикс. ΔP -> короткие окна сами требуют
    // быстрого потока, длинные ловят медленный.
    float    search_hist[SEARCH_HIST_N]; // кольцо чекпойнтов P_filt
    int32_t  search_hist_idx;       // куда писать следующий чекпойнт
    int32_t  search_hist_count;     // сколько чекпойнтов уже валидно (0..N)
    uint64_t search_hist_dt_us;     // период между чекпойнтами (= младший лаг)
    uint64_t search_hist_t0_us;     // время последнего чекпойнта
    float    search_dp_flow;        // P_filt выросло на это над чекпойнтом = поток пошёл
    float    search_warmup_rate;    // |rate_filt| ниже этого = давление устаканилось после RATE -> свипать
    uint64_t search_warmup_max_us;  // таймаут фазы прогрева (если rate_filt так и не упал)
    uint64_t search_settle_t0_us;   // таймер фазы прогрева
    int32_t  search_found_pos;      // позиция иглы, на которой обнаружен поток
    float    search_target_back;    // фаза 2 «едем до цели» финиширует не на самой цели, а на (цель - это).
                                    //  1) хвост давления / лаг P_filt доводят остаток без перелёта;
                                    //  2) КРИТИЧНО: этот порог (0.5) > порога точной цели
                                    //     (sensor_noise_delta_filt=0.03), поэтому фаза 2 успевает выставить
                                    //     dose_charge_calibrated=true ДО того, как сработает внешняя проверка
                                    //     «дошли» в SERVO_CHARGING. Иначе калибровка не фиксируется ->
                                    //     следующий НАБОР свипует порог заново и в FINE не входим (печатаем).
    int32_t  search_done_back;      // финиш фазы 2: держать иглу НЕ на флоу-позиции, а на (найденная - это)
                                    // шагов. Поток там слабее -> остаток давления добирается мягче (меньше
                                    // перелёт), ниже порога потока доза догонит +dose_trim. 0 = на самой найденной.
    int32_t  search_drive_boost;    // фаза 2 «едем до цели»: ПОКА едем, держим иглу на (найденная + это) шагов.
                                    // Порог = едва-поток (~0.05 кПа/с), проезд на нём медленный; буст даёт поток
                                    // сильнее -> доезжаем быстрее. На ФИНИШЕ буст откатываем (садимся на
                                    // найденная - search_done_back, как раньше). 0 = старое поведение (на пороге).
    // Малый шаг уставки на НАБОРЕ (до цели < search_slow_step_band, напр. 400->400.1):
    // открываем иглу ВТРОЕ медленнее (период свипа ×search_slow_step_mult). Иначе к
    // моменту старта потока угол уже открыт с запасом и крошечная цель «подлетает» с
    // перелётом (видели 400.1 -> P 400.18). Большой шаг (>= band, напр. 400->400.5)
    // свипуем как обычно — там запаса хватает. Только НАБОР (СБРОС не трогаем).
    float    search_slow_step_band; // шаг до цели < этого (кПа) -> медленный свип (НАБОР)
    int32_t  search_slow_step_mult; // во столько раз реже приращение иглы на малом шаге
    bool     search_small_step;     // true = текущий свип идёт замедленно (малый шаг НАБОРА)

    // ---- ВЫБОР РЕЖИМА УДЕРЖАНИЯ ПО УСТАВКЕ + полосы СЕРВО-ОТСЕЧКИ (bang-bang) ----
    // На НИЗКОЙ уставке (< fine_min_setpoint) точный холдинг (FINE) не сходится:
    // равновесного приоткрытия нет (приток/утечка нестационарны из-за теплового крипа),
    // игла уползает в floor, а давление продолжает дрейфовать. Поэтому ниже порога FINE
    // ОТКЛЮЧАЕМ и держим СЕРВО-ОТСЕЧКОЙ: в покое запечатано (серво нейтраль, игла floor);
    // ушло за hold_trig_band от цели -> импульс ПРЕДКАЛИБРОВАННЫМ шагом (набор
    // step_holding_charge / сброс step_holding_vent, серво в сторону) пока не вернулись
    // в hold_reseal_band, затем снова запечатано. Шаг сброса ищется лениво переборным
    // поиском при ПЕРВОМ перелёте вверх (как шаг набора при подходе снизу). Снятие на
    // ТОЙ ЖЕ стороне (reseal < trig) — гистерезис против пинг-понга набор<->сброс.
    float    fine_min_setpoint;     // уставка >= этого -> FINE как раньше; ниже -> серво-отсечка
    float    hold_trig_band;        // (низкая уставка) |err_filt| > этого из покоя -> импульс коррекции
    float    hold_reseal_band;      // (низкая уставка) вернулись ближе этого к цели -> снова запечатать
    // СБРОС-эпизод (low_mode): штуцер серво->игла после НАБОРА стоит под давлением подачи.
    // Если открыть иглу сразу, она распахивается БЫСТРЕЕ, чем серво доезжает в VENT
    // (~150 vs ~300 мс), и высокий штуцер дампит в объём -> заброс ВВЕРХ (на 50 кПа видели
    // +1.8 кПа). Поэтому сперва серво в VENT при игле во floor, выдержка hold_vent_settle_us
    // (ход серво + стравливание штуцера на атмосферу), и только потом игла на дозу сброса.
    bool     hold_vent_arming;      // true = серво в VENT, игла ждёт во floor до конца выдержки
    uint64_t hold_vent_arm_t0_us;   // момент переключения серво в VENT (старт выдержки)
    uint64_t hold_vent_settle_us;   // длительность выдержки серво->игла
    // ПРЕД-ВЫДЕРЖКА НА ПРИХОДЕ К ЦЕЛИ (только fast_mode, любое давление). В fast_mode
    // RATE отдаёт в HOLD ровно на ПЕРЕСЕЧЕНИИ цели — там транзиент (перелёт по сырому +
    // импульс скорости). Выбирать сторону набор/сброс по нему рано: ловили ложный СБРОС,
    // который вместе с утечкой проваливал далеко вниз (2000.3 -> 1996, потом откачка
    // НАБОРОМ). Поэтому на входе в HOLD держим ЗАПЕЧАТАННЫМ (серво нейтраль, игла floor)
    // hold_presettle_us — даём давлению ОТСТОЯТЬСЯ — и только потом по отстоявшемуся
    // err_filt выбираем сторону обычной логикой. Армируется в run_rate_phase (вход в
    // HOLD), одноразово на приход; снимается на новой уставке / HOLD->RATE.
    bool     hold_presettle;        // true = идёт пред-выдержка на приходе (сторону ещё не выбираем)
    uint64_t hold_presettle_t0_us;  // момент входа в пред-выдержку
    uint64_t hold_presettle_us;     // длительность пред-выдержки (даём давлению отстояться)

    // ---- ВТОРОЙ (ТОЧНЫЙ) ХОЛДИНГ: равновесное приоткрытие вместо подкачек ----
    bool     hold_fine_enable;      // КОНФИГ: true = после выхода на точку НАБОРОМ переходить в
                                    // точный холдинг; false = старое поведение (печать + эпизоды)
    bool     fine_holding;          // true = сейчас точный холдинг: серво стоит в НАБОРЕ,
                                    // игла на равновесном приоткрытии
    int32_t  fine_pos;              // текущее открытие иглы точного холдинга
    int32_t  fine_seed_back;        // ПЕРВЫЙ вход в FINE: step_holding_charge минус это
    // Переучивание на ПОВТОРНОМ входе: вместо «всегда доза-fine_seed_back» садимся на
    // ±fine_relearn_step от позиции прошлого выхода по стороне выброса (вниз -> открыть
    // больше, вверх -> прикрыть). Сходимся к равновесию мелким шагом между эпизодами.
    int32_t  fine_relearn_step;     // ±шаг переучивания позиции FINE на повторном входе
    bool     fine_visited;          // были ли уже в FINE этой уставкой (иначе вход = доза - fine_seed_back)
    int32_t  fine_last_pos;         // позиция FINE на прошлом выходе (база для переучивания)
    int32_t  fine_seed_adj;         // +-fine_relearn_step: знак по стороне прошлого выброса
    int32_t  fine_trim;             // подстройка открытия за окно (+- по знаку скорости)
    uint64_t fine_period_us;        // окно оценки знака скорости (5 с)
    float    fine_eq_band;          // |dP| за окно МЕНЬШЕ этого = «стоим»: равновесие найдено
    bool     fine_eq_found;         // равновесное открытие найдено и запомнено в fine_eq_pos
    int32_t  fine_eq_pos;           // найденное равновесное открытие: игла стоит на нём,
                                    // повторный вход FINE стартует сразу с него
    float    fine_corr_err;         // «стоим», но |err_filt| больше этого -> мягко двигаем равновесие к цели
    float    fine_dev_guard;        // FINE: |err_filt| >= этого -> НЕ двигаем иглу в сторону ОТ цели
                                    // (ниже цели не прикрываем, выше не приоткрываем; дрейф К цели не глушим)
    int32_t  fine_trim_fast;        // крупная подстройка за окно, пока давление ещё активно
                                    // движется (fine_change >= fine_hold_change) — вместо fine_trim

    // ---- ЛЕСЕНКА ШАГА: дрейф упрямо в одну сторону -> наращиваем шаг иглы ----
    // Фиксированный шаг ±fine_trim не успевал за устойчивым уводом (видели ~7 шагов
    // +1 за ~10 с, а P всё рос). Считаем СЕРИЮ подряд-дрейфов в одну сторону: пока
    // знак дрейфа не меняется, каждый РЕАЛЬНЫЙ шаг той же стороны растит величину на
    // fine_drift_step_inc за каждый шаг сверх fine_drift_run_thresh, потолок
    // fine_drift_step_cap. Серию рвёт (run->0) только реальный шаг в ДРУГУЮ сторону
    // (разворот), «стоим» (равновесное окно), grace и новая уставка. Придушенный
    // гардом тик (шумовой провал P_filt у цели = отрицательный лаг выше цели) серию
    // НЕ трогает — иначе шум на 1 тик сбивал лесенку обратно на 1.
    int32_t  fine_drift_run;         // длина текущей серии подряд-дрейфов в одну сторону
    int32_t  fine_drift_sign;        // знак дрейфа этой серии (+1 рост / −1 падение; 0 = серии нет)
    uint64_t fine_drift_grace_seen;  // последнее fine_grace_t0_us, на котором гасили серию: новое
                                     // grace-окно (вход/разворот) сбрасывает серию ОДИН раз, не каждый тик
    int32_t  fine_drift_run_thresh;  // расти начинаем, когда серия длиннее этого (КОНФИГ)
    int32_t  fine_drift_step_inc;    // на сколько растёт шаг за каждый дрейф сверх порога (КОНФИГ)
    int32_t  fine_drift_step_cap;    // потолок величины шага иглы при лесенке (КОНФИГ)
    float    fine_change;           // |ΔP_filt| за последние ~5 с (скользящее окно) — гейт FINE->HOLD
    float    fine_hold_change;      // fine_change >= этого = «ещё движусь»: остаёмся в FINE,
                                    // крупный шаг, в HOLD не уходим (защита от дёрганья у порога)
    uint64_t fine_rate_t0_us;       // трекер fine_change: начало текущего чекпойнта (мкс)
    float    fine_rate_p_cur;       // P_filt на последнем чекпойнте (0..period/2 назад)
    float    fine_rate_p_prev;      // P_filt на предыдущем чекпойнте (period/2..period назад)

    // ---- РАЗВОРОТ НАПРАВЛЕНИЯ, КОГДА ИГЛА FINE УПЁРЛАСЬ В НОЛЬ ----
    // Дрейф-алгоритм FINE прикрывает иглу, когда текущее направление перебарщивает.
    // Если он закрыл её почти в ноль (fine_pos < fine_flip_floor), а равновесия так и
    // нет — значит удерживаем НЕ ТЕМ направлением: дрейф упрямо идёт туда, куда это
    // направление толкать не может (НАБОР закрылся в ноль, а P всё растёт -> нужен
    // СБРОС; зеркально для сброса). Разворачиваем серво и стартуем FINE заново с
    // маленького приоткрытия fine_flip_floor — БЕЗ поиска порога/дозы, дальше его
    // растит сам дрейф-алгоритм. То же число служит и порогом срабатывания, и стартовым
    // открытием после разворота; grace-окно гасит повторный разворот, пока новое
    // направление набирает открытие.
    int32_t  fine_flip_floor;       // fine_pos упал ниже этого -> развернуть направление и стартовать с него

    // ---- НОВЫЙ ЭТАП «ПОИСК СКОРОСТИ»: выбор направления удержания по дрейфу ----
    // После выхода на точку и 1с паузы объём ДЕРЖИМ запечатанным (серво нейтраль,
    // игла floor) ещё fine_ss_period_us и смотрим, куда сам поплыл P_filt:
    //   dP < 0  (утечка)      -> удерживаем НАБОРОМ (серво CHARGING);
    //   dP >= 0 (ползёт вверх) -> удерживаем СБРОСОМ (серво VENTING).
    // Направление больше НЕ берётся из стороны подхода. Полярность ±шага иглы
    // дальше задаёт sgn из servo_state (hold_fine_step).
    bool     fine_speed_search;     // true = идёт замер дрейфа после 1с паузы
    uint64_t fine_ss_t0_us;         // начало окна замера (мкс)
    float    fine_ss_p0;            // P_filt, зафиксированное в начале окна
    uint64_t fine_ss_period_us;     // длительность замера дрейфа (2 с)
    float    fine_ss_seal_band;     // |дрейф за fine_ss_period_us| МЕНЬШЕ этого = объём держит давление
                                    // САМ -> FINE НЕ включаем, просто перекрываем всё (игла 0, серво
                                    // нейтраль) и уходим в обычный HOLD. Направление при этом не фиксируем
    float    fine_ss_vent_offset;   // ПОДХОД СБРОСОМ (п.2): замер дрейфа запечатываем не на цели, а на
                                    // (цель + это) — даём запас вниз на просадку за 1с+замер. Утечка за
                                    // время замера опустит P к цели (дальше держим НАБОРОМ — поиск порога
                                    // накачки), всплытие лечится СБРОСОМ (поиск порога сброса). На цели
                                    // замерять нельзя: утечка увела бы P ниже цели уже в момент замера
    float    fine_ss_charge_offset; // ПОДХОД НАБОРОМ: зеркально vent_offset — замер запечатываем на
                                    // (цель − это), запас ВВЕРХ на всплытие за время паузы/замера
    // ---- ДОП.ПРОВЕРКА ТОЛЬКО ДЛЯ НАКАЧИВАНИЯ (в первой паузе перед замером дрейфа) ----
    // Пауза first_in_fine для прихода НАБОРОМ делится: первые fine_ss_charge_precheck_us —
    // обычная пауза (запечатано), следующие до конца паузы — проверка направления. По её
    // итогу: давление ПАДАЕТ -> утечка, сразу держим НАБОРОМ (в замер дрейфа НЕ идём);
    // РАСТЁТ -> идём в обычный замер дрейфа fine_ss_period_us и решаем там (как при СБРОСЕ).
    bool     ss_from_charge;            // true = текущая пауза/замер запущены приходом НАБОРОМ (не СБРОСОМ)
    uint64_t fine_ss_charge_precheck_us;// длительность чистой паузы до начала доп.проверки (2.5 с)
    float    ss_check_p0;               // P_filt на старте доп.проверки (для знака за окно проверки)
    uint64_t fine_grace_t0_us;      // момент входа в FINE из «поиска скорости»: гейт FINE->HOLD
                                    // молчит первые fine_period_us (даём FINE вернуть P к цели иглой,
                                    // иначе дрейф за 1с+2с запечатывания сразу выкинул бы в HOLD)
    ServoState fine_dir;            // ЗАПОМНЕННОЕ направление удержания (НАБОР/СБРОС): определяется
                                    // замером дрейфа ОДИН раз на уставку и переиспользуется
    bool       fine_dir_known;      // направление уже определено для текущей уставки; сбрасывается
                                    // ТОЛЬКО в reset_controllers (новая уставка / idle / homing / leak)
    bool       fine_after_speed_search; // true = текущий эпизод FINE — ПЕРВЫЙ сразу после замера дрейфа.
                                    // Недолёт P до цели здесь = недобранная просадка от 1с паузы + замера
                                    // (объём был запечатан, травил), а НЕ «равновесие низкое» -> на хэндофе
                                    // в HOLD НЕ переучиваем (+relearn/срез дозы перельют: повторный вход
                                    // идёт по fine_dir_known БЕЗ паузы/замера, значит уже БЕЗ просадки).
                                    // Снимается, как только P вернулось к цели или на самом хэндофе.

    // ---- лимиты привода ----
    int32_t valve_max;              // макс. открытие иглы (шаги)
    int32_t valve_flow_floor;       // открытие, ниже которого игла НЕ пропускает газ (мёртвый ход)
    int32_t max_step;               // макс. сдвиг иглы за один тик (плавность/защита)
} PressureRegulator;

