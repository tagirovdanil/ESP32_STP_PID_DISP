#pragma once

#include <stdbool.h>
#include <stdint.h>

/*
 * ============================================================================
 *  КОНФИГУРАЦИЯ: КОНТРОЛЛЕР ДВУХ КОМПРЕССОРОВ
 * ============================================================================
 *  Устройство управляет двумя компрессорами (реле вкл/выкл) по показаниям двух
 *  независимых датчиков давления. Датчики имеют одинаковый адрес, поэтому каждый
 *  подключён на ОТДЕЛЬНУЮ UART-шину:
 *    канал 1: датчик №1 (UART1, RX26/TX27) -> компрессор 1
 *    канал 2: датчик №2 (UART2, RX12/TX13) -> компрессор 2
 *
 *  Закон управления — гистерезис вокруг уставки канала:
 *    вкл при  P < SET - COMP_HYST_KPA
 *    выкл при P >= SET
 *  (небольшая гистерезис-зона защищает реле от дребезга на границе уставки).
 */

// ----- Выходы реле компрессоров (активный уровень — HIGH) -----
#define PIN_COMP1   21
#define PIN_COMP2   22

// Гистерезис включения компрессора, кПа
#define COMP_HYST_KPA  2.0f

// Верхний предел уставки, кПа
#define SETPOINT_MAX_KPA 4000.0f

// ----- Глобальные переменные (определены в config.c / pressure_sensor.c) -----
extern volatile float pressure1_kPa;   // давление канала 1 (датчик №1)
extern volatile float pressure2_kPa;   // давление канала 2 (датчик №2)
extern volatile float setpoint1_kPa;   // уставка канала 1
extern volatile float setpoint2_kPa;   // уставка канала 2
extern volatile bool  is_calibrating;  // идёт калибровка нуля датчика (пауза экрана)

// ----- Прототипы -----
// Установка уставки канала (1 или 2) с ограничением диапазона.
void update_setpoint(uint8_t channel, float new_setpoint);
