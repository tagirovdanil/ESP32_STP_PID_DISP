#pragma once

#include <stdbool.h>
#include <stdint.h>
#include "driver/uart.h"

/*
 * ============================================================================
 *  КОНФИГУРАЦИЯ: ДВУХСТУПЕНЧАТАЯ КОМПРЕССОРНАЯ УСТАНОВКА
 * ============================================================================
 *  Два датчика давления (в кПа; 1 МПа = 1000 кПа), диапазон 0..4000 кПа:
 *    P1 = давление после 1-й ступени (датчик №1, UART1, RX26/TX27)
 *    P2 = давление после 2-й ступени (датчик №2, UART2, RX23/TX25)
 *  Два компрессора (реле, активный уровень HIGH):
 *    K1 = 1-я ступень (GPIO2),  K2 = 2-я ступень (GPIO17)
 *  Внешний дисплей (HMI) по UART0, пины переназначены на GPIO21 (TX)/GPIO22(RX),
 *  протокол NMEA: $SLSD от нас, $SLSS/$SLSC от дисплея (см. protocol.txt).
 *
 *  Прошивка не ломается: ROM-загрузчик общается по GPIO1/3 (UART0 по умолчанию).
 *  Логи ESP-IDF отключены пользователем (console = none), поэтому в UART0 идут
 *  только кадры протокола.
 */

// ----- Реле компрессоров (активный уровень — HIGH) -----
#define PIN_COMP1       2
#define PIN_COMP2       17

// ----- Уставка P2 (кПа): диапазон 1,0..4,0 МПа -----
#define P2_SET_MIN_KPA      1000.0f
#define P2_SET_MAX_KPA      4000.0f
#define P2_SET_DEFAULT_KPA  1000.0f   // уставка по умолчанию при включении: 1,0 МПа
#define P2_START_DROP_KPA   400.0f    // повторное включение K2: P2_Set - 0,4 МПа

// ----- Пороги давления (кПа), 1 МПа = 1000 кПа -----
#define P1_ON_KPA      800.0f    // P1 <= 0,8 МПа  -> K1 ВКЛ
#define P1_OFF_KPA    1000.0f    // P1 >= 1,0 МПа  -> K1 ВЫКЛ
#define P_SYNC_ON_KPA  800.0f    // синхронный режим (P2_Set = 1,0): вкл при P2 <= 0,8
#define P_SYNC_OFF_KPA 1000.0f   // синхронный режим: выкл при P2 >= 1,0

// ----- Диагностика отсутствия сжатия (подбирается при наладке) -----
#define DIAG_WINDOW_MS    3000    // T_Diag, окно оценки роста давления
#define D_P1_MIN_KPA      10.0f   // минимальный рост P1 за окно
#define D_P2_MIN_KPA      10.0f   // минимальный рост P2 за окно
#define RESTART2_MS       20000   // пауза повторного запуска K2
#define RETRY2_MAX        3       // макс. число повторных запусков K2
#define WARMUP_MS         1000    // выход 2-й ступени на режим до начала диагностики

// ----- Контроль датчиков -----
#define SENSOR_STALE_MS   1500    // нет валидного кадра дольше — связь потеряна
#define PRESSURE_MAX_KPA  4100.0f // верхняя отсечка "битых" показаний (датчик до 4 МПа)
#define PRESSURE_MIN_KPA  -10.0f  // нижняя граница с допуском: атмосфера может чуть уходить в "-"

// ----- UART связи с внешним дисплеем (UART0, TX=GPIO21, RX=GPIO22) -----
#define DISPLAY_UART_NUM    UART_NUM_0
#define PIN_DISP_TX         21
#define PIN_DISP_RX         22
#define DISPLAY_UART_BAUD   115200
#define DISPLAY_SEND_MS     200     // период отправки $SLSD на дисплей

/* ============================================================================
 *  БЕЗОПАСНЫЙ РЕЖИМ («ЗАГЛУШКИ») — НИ ОДИН ВЫВОД НЕ ПЕРЕКЛЮЧАЕТСЯ
 * ============================================================================
 *  1 = прошивка не занимает и не дёргает ни один GPIO: не вызываются
 *      gpio_config()/gpio_set_level(), не устанавливаются драйверы
 *      UART0/1/2 и не вызывается uart_set_pin() (пины 21/22, 25/26/27/33
 *      остаются «в воздухе»), не поднимается SPI и не инициализируется
 *      ST7789 (пины 18/19/5/16/23/4), не запускаются задачи отрисовки.
 *      Живыми остаются: WiFi/TCP-сервер, приём команд и логика автомата
 *      (реле только меняют переменные состояния, физически — ничего).
 *  0 = боевой режим (реальная работа с железом).
 *
 *  Нужен при переносе прошивки на другую плату, пока распиновка не сверена:
 *  иначе выводы прошивки (SPI LCD, UART датчиков) попадают на входы реле и
 *  реле начинают беспорядочно клацать.
 *
 *  Подробная таблица выводов и причины клацанья — в СПРАВКА_ПОРТЫ.md.
 * ========================================================================== */
#define SAFE_NO_PINS        0

// ----- Глобальные переменные (определены в config.c / pressure_sensor.c) -----
extern volatile float pressure1_kPa;   // датчик №1 (P1), кПа
extern volatile float pressure2_kPa;   // датчик №2 (P2), кПа
extern volatile float p2_set_kPa;      // уставка P2, кПа (по умолчанию 4000)
extern volatile bool  is_calibrating;  // идёт калибровка нуля датчика
