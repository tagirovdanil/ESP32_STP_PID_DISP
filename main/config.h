#pragma once

#include <stdbool.h>
#include <stdint.h>
#include "driver/uart.h"

/*
 * ============================================================================
 *  КОНФИГУРАЦИЯ: ДВУХСТУПЕНЧАТАЯ КОМПРЕССОРНАЯ УСТАНОВКА
 * ============================================================================
 *  Два датчика давления (в кПа; 1 МПа = 1000 кПа), рабочий диапазон 0..4200 кПа:
 *    P1 = давление после 1-й ступени (датчик №1, адрес 0x01)
 *    P2 = давление после 2-й ступени (датчик №2, адрес 0x02)
 *  Компрессоры (реле с оптопарой — управление РЕВЕРСИВНОЕ, активный LOW):
 *    K1 = 1-я ступень (GPIO21), K2 = 2-я ступень (GPIO22)
 *    K3 = резерв (GPIO17),      K4 = резерв (GPIO2)
 *    K3/K4 автоматом не управляются, но участвуют в демо-проверке (команда DEMO).
 *    Полярность задаётся RELAY_ACTIVE_LOW: 1 = LOW включает реле.
 *
 *  РАСКЛАДКА UART:
 *    UART1 -> ОБЩАЯ шина датчиков: 0x01 и 0x02, RX=GPIO26, TX=GPIO27.
 *             Опрос по кругу: каждый запрос — со своим адресом, пауза между
 *             запросами равна SENSOR_POLL_INTERVAL_MS.
 *    UART2 -> внешний дисплей (HMI), TX=GPIO33, RX=GPIO25, NMEA:
 *             $SLSD от нас, $SLSS/$SLSC от дисплея (см. PANEL_PROTOCOL.md).
 *    UART0 -> консоль/логи ESP-IDF (GPIO1/3, COM-порт),
 *             CONFIG_ESP_CONSOLE_UART_DEFAULT=y в sdkconfig.
 *
 *  Почему дисплей уведён с 21/22: эти выводы отданы реле K1/K2,
 *  а 33/25 всё равно освободились после перевода датчика №2 на общую UART1.
 *  GPIO33/25 — обычные выводы, не strapping, ранее проверены на этой плате.
 *  GPIO2 (K4) — strapping: при старте на нём не должно быть внешнего HIGH.
 *
 *  ВНИМАНИЕ: GPIO23 занят сбросом (RST) локального экрана ST7789 —
 *  на него ничего подключать нельзя (см. PIN_RST в pressure_sensor.h).
 *  GPIO12 и GPIO15 не занимать реле: 12 — strapping MTDI (VDD_SDIO, 1.8 В
 *  flash при внешнем HIGH), 15 — strapping MTDO с внутренней подтяжкой вверх.
 */

// ----- Реле компрессоров -----
// 1 = активный LOW (модули реле с оптопарой: LOW на входе -> реле ВКЛ)
// 0 = активный HIGH (обычные ключи/транзисторы: HIGH -> реле ВКЛ)
#define RELAY_ACTIVE_LOW    1

#define PIN_COMP1       21   // K1: 1-я ступень
#define PIN_COMP2       22   // K2: 2-я ступень
#define PIN_COMP3       17   // K3: резерв (участвует в демо)
#define PIN_COMP4       2    // K4: резерв (участвует в демо; strapping-пин!)

// ----- Уставка P2 и порог повторного включения (кПа), 1 МПа = 1000 кПа -----
// Диапазон приёма соответствует панели (PANEL_PROTOCOL.md §4.1):
//   P2_Set = 0.35..4.20 МПа, P2_Start = 0.25..(P2_Set - 0.10) МПа.
// Принимаемая и ПРИМЕНЯЕМАЯ уставка — одна и та же граница 4.20 МПа: раньше
// применяемая уставка «обрезалась» до 4.00 МПа, и при задании 4.1…4.2 установка
// останавливалась на 4.00 (компрессор «не добирал» уставку). Потолок снят.
#define P2_SET_MIN_KPA       350.0f    // нижняя граница приёма, кПа
#define P2_SET_MAX_KPA       4200.0f   // верхняя граница приёма, кПа
#define P2_SET_APPLY_MAX_KPA 4200.0f   // предел применения = предел приёма
#define P2_SET_DEFAULT_KPA   4000.0f   // по умолчанию, как на панели: 4.00 МПа
// Жёсткий предел перепуска: P2 >= P2_Set + P2_OVERSHOOT_KPA -> авария и останов
// независимо от режима (RUN, STOP, SERVICE, демо) и от диагностики
// (PANEL_PROTOCOL.md §7.2). Проверяется КАЖДЫЙ такт, до всей остальной логики.
#define P2_OVERSHOOT_KPA     100.0f    // допустимый перепуск сверх уставки, кПа
// Порог повторного включения K2 (P2_Start) приходит с панели:
//   $SLSS,<P2_Set>,<P2_Start>*<HH>, например $SLSS,3.60,3.20*1B
// Если панель прислала только уставку (старый формат $SLSS,<P2_Set>),
// порог пересчитывается как MAX(1.0; P2_Set - 0.4) с ограничением P2_Set - 0.1.
#define P2_START_DROP_KPA    400.0f    // резерв, если P2_Start не передан: P2_Set - 0,4 МПа
#define P2_START_MIN_KPA     250.0f    // нижняя граница P2_Start
#define P2_MIN_GAP_KPA       100.0f    // минимальный зазор P2_Set - P2_Start
#define P2_START_DEFAULT_KPA 3600.0f   // по умолчанию, как на панели: 3.60 МПа

// ----- Пороги давления (кПа), 1 МПа = 1000 кПа -----
// Пороги 1-й ступени фиксированы: ВП1 = 1000 кПа, гистерезис 300 кПа
// (уточнение заказчика 2026-11-06) => НП1 = 700 кПа.
// Пользовательских порогов ступеней нет: уставка и порог повторного включения
// 2-й ступени приходят только кадром $SLSS.
#define P1_ON_KPA           700.0f    // P1 <= 0,7 МПа  -> K1 ВКЛ (гистерезис 300 кПа)
#define P1_OFF_KPA         1000.0f    // P1 >= 1,0 МПа  -> K1 ВЫКЛ
// Пуск 2-й ступени (K2) разрешён только после набора P1 до этого уровня.
// Требование заказчика (2026-11-09): при уставке выше 1 МПа K2 не включать,
// пока первая ступень не набрала минимум 700 кПа. В синхронном режиме
// (уставка ровно 1,0 МПа) ограничение не применяется.
#define K2_START_P1_KPA     700.0f
// Кадр $SLSC,TH — справочный: только проверка корректности/согласованности.
#define P_TH_MIN_KPA         50.0f    // минимальный порог ступени в кадре TH
#define P_TH_MAX_KPA       4200.0f    // максимальный порог ступени в кадре TH
#define P_TH_MIN_GAP_KPA     50.0f    // минимальный зазор НП/ВП ступени в кадре TH
#define P_SYNC_SET_KPA    1000.0f    // уставка, при которой включается синхронный режим
#define P_SYNC_ON_KPA      800.0f    // синхронный режим (P2_Set = 1,0): вкл при P2 <= 0,8
#define P_SYNC_OFF_KPA    1000.0f    // синхронный режим: выкл при P2 >= 1,0

// ----- Ограничение непрерывной работы компрессоров -----
// Если K1 или K2 проработал непрерывно больше COMP_MAX_CONT_RUN_MS,
// ему принудительно даётся отдых не меньше COMP_MIN_REST_MS (по каждому отдельно).
#define COMP_MAX_CONT_RUN_MS  (10u * 60u * 1000u)  // 10 минут непрерывной работы
#define COMP_MIN_REST_MS      ( 5u * 60u * 1000u)  // 5 минут отдыха

// ----- Диагностика отсутствия сжатия (подбирается при наладке) -----
#define DIAG_WINDOW_MS    3000    // T_Diag, окно оценки роста давления
#define D_P1_MIN_KPA      10.0f   // минимальный рост P1 за окно
#define D_P2_MIN_KPA      10.0f   // минимальный рост P2 за окно
#define RESTART2_MS       20000   // пауза повторного запуска K2
#define RETRY2_MAX        3       // макс. число повторных запусков K2
#define WARMUP_MS         1000    // выход 2-й ступени на режим до начала диагностики

// ----- Стартовая пауза -----
// Даём внешнему дисплею время подняться: силовые выводы (реле), датчики и
// передача $SLSD на панель (UART2 TX=33) начинаются только после паузы.
// ВАЖНО: приём на UART2 (RX=25) работает УЖЕ С ПЕРВОЙ МИЛЛИСЕКУНДЫ — кадр
// $SLSS, который панель шлёт при своём включении, не теряется.
// 0 = без паузы.
#define STARTUP_DELAY_MS    4000

// ----- Демо-проверка реле (команда DEMO, останов — DEMOSTOP/STOP) -----
// Непрерывный цикл: K1 ON -> K2 ON -> K3 ON -> K4 ON ->
//                   K4 OFF -> K3 OFF -> K2 OFF -> K1 OFF -> повтор
#define RELAY_DEMO_HOLD_MS  3000   // пауза между переключениями реле, мс

// ----- Опрос датчиков на общей шине UART1 -----
#define SENSOR_POLL_INTERVAL_MS  50  // пауза между запросами к датчикам (0x01 -> 0x02)
                                     // => каждый датчик опрашивается раз в 2*50 = 100 мс

// ----- Контроль датчиков -----
#define SENSOR_STALE_MS   1500    // нет валидного кадра дольше — связь потеряна
// Отсечка заведомо «битых» показаний. Должна быть ВЫШЕ максимальной уставки
// плюс перепуск (4.20 + 0.10 = 4.30 МПа), иначе исправные показания выше 4.1 МПа
// отбрасывались и взводилась авария датчика 2, из-за чего уставка 4.2 была
// недостижима даже без программного ограничения уставки.
#define PRESSURE_MAX_KPA  5000.0f
// Нижняя граница: отрицательное давление — НЕ авария. Нуль датчика плывёт из-за
// атмосферного давления (реально -30...-60 кПа), поэтому снизу аварии нет.
// Авария 2 только по верхнему пределу и по потере связи с датчиком;
// отрицательный ноль убирается обнулением ($SLSC,ZERO,<n>).
// -1000 кПа — грубая отсечка явного мусора/обрыва, а не "нулевой дрейф".
#define PRESSURE_MIN_KPA  -1000.0f
// Обнуление модулей давления ($SLSC,ZERO,<n>): разрешено только при |P| < 25 кПа
#define ZERO_MAX_ABS_KPA    25.0f

// ----- UART связи с внешним дисплеем (UART2, TX=GPIO33, RX=GPIO25) -----
#define DISPLAY_UART_NUM    UART_NUM_2
#define PIN_DISP_TX         33   // линия TX контроллера -> RX дисплея
#define PIN_DISP_RX         25   // линия RX контроллера <- TX дисплея
#define DISPLAY_UART_BAUD   115200
#define DISPLAY_SEND_MS     200     // период отправки $SLSD на дисплей
#define DISPLAY_RX_MAX      256     // максимальная длина строки на приёме (как на панели)
#define DISPLAY_LINK_MS     1000    // нет кадров от панели дольше — флаг NO_LINK в state
#define CONTROL_TICK_MS      20     // такт автомата (PANEL_PROTOCOL.md §13)

// ----- Автоматика реле R3 (охлаждение) и резерва R4 -----
// R3 = (K1 || K2), после выключения ОБОИХ компрессоров держим ещё T_COOL_R3_MS.
// R4 — резерв, штатно всегда выключен.
#define T_COOL_R3_MS        60000   // выдержка реле охлаждения, мс

// ----- Сервисный тест выходов ($SLSC,OUT) -----
// Разрешён только в STOP при P1,P2 < SERVICE_MAX_P_KPA и без аварий.
#define T_TEST_COMP_MS      60000   // максимальное время теста K1/K2, мс
#define T_TEST_R4_MS        10000   // автоотключение теста резервного R4, мс
#define SERVICE_MAX_P_KPA    100.0f // «холодная» установка: P1 и P2 < 0,1 МПа

/* ============================================================================
 *  БЕЗОПАСНЫЙ РЕЖИМ («ЗАГЛУШКИ») — НИ ОДИН ВЫВОД НЕ ПЕРЕКЛЮЧАЕТСЯ
 * ============================================================================
 *  1 = прошивка не занимает и не дёргает ни один GPIO: не вызываются
 *      gpio_config()/gpio_set_level(), не устанавливаются драйверы
 *      UART0/1/2 и не вызывается uart_set_pin() (пины 25/26/27/33 и 21/22
 *      остаются «в воздухе»), не поднимается SPI и не инициализируется
 *      ST7789 (пины 18/19/5/16/23/4), не запускаются задачи отрисовки.
 *      Живыми остаются: WiFi/TCP-сервер, приём команд и логика автомата
 *      (реле только меняют переменные состояния, физически — ничего).
 *  0 = боевой режим (реальная работа с железом).
 *
 *  Нужен при переносе прошивки на другую плату, пока распиновка не сверена:
 *  иначе выводы прошивки (SPI LCD, UART датчиков) попадают на входы реле и
 *  реле начинают беспорядочно клацать.
 *
 *  Подробная таблица выводов и причины клацанья — в PANEL_PROTOCOL.md §2.
 * ========================================================================== */
#define SAFE_NO_PINS        0

// ----- Глобальные переменные (определены в config.c / pressure_sensor.c) -----
extern volatile float pressure1_kPa;   // датчик №1 (P1), кПа
extern volatile float pressure2_kPa;   // датчик №2 (P2), кПа
extern volatile float p2_set_kPa;      // уставка P2, кПа
extern volatile float p2_start_kPa;    // порог повторного включения K2, кПа
extern volatile uint32_t panel_last_rx_ms; // время последнего байта от панели, мс
// Всего завершённых строк, принятых от панели с момента включения.
// Показывается в STATE как rx=N: нажали кнопку на панели -> N должно вырасти.
extern volatile uint32_t panel_rx_frames_total;
// Сколько раз панель прислала уставку: $SLSS (slss=) и $SLSC,TH (th=).
// Нужно для диагностики: slss=0 th=1 -> панель шлёт только TH (и то один раз).
extern volatile uint32_t panel_slss_count;
extern volatile uint32_t panel_th_count;
// Время (мс, esp_timer) последней УСПЕШНО применённой уставки от панели.
// 0 = уставка от панели не применялась ни разу. В STATE печатается как set_age.
extern volatile uint32_t panel_slss_last_ms;
extern volatile bool  is_calibrating;  // идёт калибровка нуля датчика
