#ifndef SETTINGS_H
#define SETTINGS_H

#include <stdbool.h>

/*
 * ============================================================================
 *  settings.c — энергонезависимое хранение уставки (NVS)
 * ============================================================================
 *  Хранится только то, что задаёт панель кадром $SLSS:
 *    - P2_Set   (уставка, кПа);
 *    - P2_Start (порог повторного включения, кПа).
 *  Порогов ступеней в NVS больше нет (panel2_task_overshoot.md §5.3):
 *  S1 = 600/1000 кПа фиксированы алгоритмом, S2 — это те же P2_Start/P2_Set.
 *  Дисплей свою уставку не помнит, поэтому после перезагрузки любого узла
 *  источником истины остаётся мастер.
 * ============================================================================ */

// Инициализировать NVS и прочитать сохранённые P2_Set/P2_Start в p2_set_kPa и
// p2_start_kPa. Если записи нет — остаются значения по умолчанию (4.00/3.60 МПа).
// Устаревшие ключи с порогами (np1/vp1/np2/vp2) удаляются.
void settings_init(void);

// Сохранить уставку и порог повторного включения.
void settings_save_pressure_task(void);

#endif // SETTINGS_H
